from enum import StrEnum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field


class Lang(StrEnum):
    ru = "ru"
    kk = "kk"
    en = "en"


class Criticality(StrEnum):
    low = "low"
    medium = "medium"
    high = "high"


class IncidentLevel(StrEnum):
    normal = "normal"
    attention = "attention"
    critical = "critical"


class Confidence(StrEnum):
    low = "low"
    medium = "medium"
    high = "high"


class RiskBand(StrEnum):
    low = "low"
    medium = "medium"
    high = "high"


class InputKind(StrEnum):
    voice = "voice"
    audio = "audio"
    photo_tool = "photo_tool"
    photo_panel = "photo_panel"
    photo_part = "photo_part"
    text = "text"


class Profile(StrEnum):
    metalworking = "metalworking"
    bakery = "bakery"
    confectionery = "confectionery"
    sewing = "sewing"
    dairy = "dairy"


class FiboBaseModel(BaseModel):
    model_config = ConfigDict(extra="forbid")


class Usage(BaseModel):
    model_config = ConfigDict(extra="ignore")

    asr_seconds: float = Field(0.0, description="Seconds of audio processed by ASR")
    llm_input_tokens: int = Field(0, description="Tokens sent to LLM")
    llm_output_tokens: int = Field(0, description="Tokens generated by LLM")
    vision_calls: int = Field(0, description="Number of vision model invocations")
    embed_calls: int = Field(0, description="Number of embedding model invocations")
    est_cost_usd: float = Field(0.0, description="Estimated total request cost in USD")


class BaseResponse(BaseModel):
    model_config = ConfigDict(extra="ignore")

    request_id: str = Field(..., description="Unique request UUID")
    model_version: str = Field("0.1.0-stub", description="Active model release version")
    config_version: str = Field("2026.11", description="Active configuration version")
    degraded: list[str] = Field(
        default_factory=list, description="List of components operating in degraded/fallback mode"
    )
    usage: Usage = Field(default_factory=lambda: Usage(), description="Resource and token usage accounting")


class ErrorDetail(BaseModel):
    model_config = ConfigDict(extra="ignore")

    code: str = Field(..., description="UPPER_SNAKE error code")
    message: str = Field(..., description="Human-readable explanation of error")
    retriable: bool = Field(False, description="Whether client may retry this exact request")
    details: dict[str, Any] = Field(default_factory=dict, description="Structured diagnostics or retake hints")


class ErrorResponse(BaseModel):
    model_config = ConfigDict(extra="ignore")

    error: ErrorDetail
