def reason_text(reason: str, lang: str | None) -> str:
    """The backend's panel-reading rejection reason (English) in the user's language."""
    if reason.startswith("outside valid range "):
        return t(lang, "reason_range", range=reason.removeprefix("outside valid range ").replace("..", "–"))
    if reason == "not readable":
        return t(lang, "reason_unreadable")
    if reason == "field not used by this profile":
        return t(lang, "reason_unknown")
    return reason


def t(lang: str | None, key: str, **values) -> str:
    table = TEXTS.get(lang or "ru", TEXTS["ru"])
    return table[key].format(**values) if values else table[key]


