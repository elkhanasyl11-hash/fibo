"""Attachments table: files that belong to an incident.

Uploaded by the user: voice, audio (machine sound), photo.
Generated by the pipeline: spectrogram (baseline vs. current sound), heatmap (photo comparison).
file_path is relative to media_dir; the dashboard loads it through GET /media/{path}.
"""

from typing import TYPE_CHECKING

from sqlalchemy import CheckConstraint, ForeignKey, String
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base, TimestampMixin

if TYPE_CHECKING:
    from app.models.incident import Incident

ATTACHMENT_KINDS = ("voice", "audio", "photo", "spectrogram", "heatmap")


class Attachment(TimestampMixin, Base):
    __tablename__ = "attachments"
    __table_args__ = (
        CheckConstraint("kind IN ('voice', 'audio', 'photo', 'spectrogram', 'heatmap')", name="kind"),
    )

    id: Mapped[int] = mapped_column(primary_key=True)
    incident_id: Mapped[int] = mapped_column(ForeignKey("incidents.id", ondelete="CASCADE"), index=True)
    kind: Mapped[str] = mapped_column(String(20))
    file_path: Mapped[str] = mapped_column(String(500))

    incident: Mapped["Incident"] = relationship(back_populates="attachments")
