"""Web sign-up / sign-in and the onboarding survey.

The survey is what the owner answers before creating the account (what the workshop does, team,
shifts) plus the industry questions (generated by AI or taken from the built-in set). It is stored
as JSON on the workshop and used as context for AI advice.
"""

from typing import Literal

from pydantic import BaseModel, Field, field_validator

from app.db.base import Profile
from app.schemas.user import Language, UserRead
from app.schemas.workshop import WorkshopRead

EMAIL_PATTERN = r"^[^@\s]{1,64}@[^@\s]{1,189}\.[^@\s]{2,}$"
TeamSize = Literal["1-5", "6-20", "21-50", "50+"]


class SurveyAnswer(BaseModel):
    question_id: str = Field(min_length=1, max_length=60)
    question: str = Field(min_length=1, max_length=200)
    answer: str | list[str] | float = Field(description="Text, chosen options, or a number")


class WorkshopSurvey(BaseModel):
    activity: str = Field(default="", max_length=300, description="What the workshop does, own words")
    team_size: TeamSize | None = None
    shifts: int | None = Field(default=None, ge=1, le=3)
    machine_count: int | None = Field(default=None, ge=0, le=500)
    goals: list[str] = Field(default_factory=list, max_length=8)
    answers: list[SurveyAnswer] = Field(default_factory=list, max_length=30)
    questions_source: Literal["ai", "builtin"] | None = None


class WorkshopInfo(BaseModel):
    @field_validator("name", "city", mode="before")
    @classmethod
    def trim_labels(cls, value: str) -> str:
        return value.strip() if isinstance(value, str) else value

    name: str = Field(min_length=1, max_length=150)
    city: str = Field(default="Шымкент", min_length=1, max_length=100)
    profile: Profile


class RegisterRequest(BaseModel):
    @field_validator("email", "full_name", mode="before")
    @classmethod
    def trim_identity(cls, value: str) -> str:
        return value.strip() if isinstance(value, str) else value

    email: str = Field(pattern=EMAIL_PATTERN, max_length=254)
    password: str = Field(min_length=8, max_length=128)
    full_name: str = Field(min_length=1, max_length=150)
    language: Language = "ru"
    workshop: WorkshopInfo
    survey: WorkshopSurvey | None = None


class LoginRequest(BaseModel):
    email: str = Field(max_length=254)
    password: str = Field(max_length=128)


class AuthResponse(BaseModel):
    token: str = Field(description="Send as Authorization: Bearer <token>")
    user: UserRead
    workshop: WorkshopRead
    telegram_link: str | None = Field(description="t.me deep link that joins this workshop in the bot")


class TelegramLinkResponse(BaseModel):
    link: str | None = Field(description="t.me deep link; None when the bot username is not configured")
    expires_at: int = Field(description="Unix time; the link stops working after it")
    linked: bool = Field(description="True if this account already has Telegram")


class BotLink(BaseModel):
    telegram_id: int = Field(gt=0)
    token: str = Field(min_length=8, max_length=64, pattern=r"^[A-Za-z0-9_-]+$")


class Question(BaseModel):
    id: str = Field(min_length=1, max_length=60, pattern=r"^[a-z0-9_]+$")
    label: str = Field(min_length=1, max_length=200)
    help: str = Field(default="", max_length=300)
    kind: Literal["single", "multi", "text", "number"]
    options: list[str] = Field(default_factory=list, max_length=10)
    unit: str = Field(default="", max_length=20)


class QuestionsRequest(BaseModel):
    profile: Profile
    activity: str = Field(default="", max_length=300)
    language: Language = "ru"


class QuestionsResponse(BaseModel):
    source: Literal["ai", "builtin"]
    questions: list[Question] = Field(max_length=8)
    degraded: list[str] = Field(default_factory=list, description="Why the built-in set was used")
